
'''
Renderer-free font metrics (SPEC-09A §6).

AST asks its graphics backend two questions while laying out a plot: how tall
is a character (``Qch``) and how big is the box around this string (``TxExt``).
Answering them from a *shipped table* rather than from a live renderer is what
makes SkyPlot v2's layout identical in an SVG file, a notebook, a browser, and
a matplotlib window (D17) — ``grf_matplotlib`` answers ``TxExt`` by drawing
into the live figure, so its layout differs per backend and per DPI.

The table is generated by ``source/scripts/generate_font_metrics.py``; neither
fontTools nor matplotlib is a runtime dependency.
'''

import json
import logging
import math
from typing import Optional, Tuple

__all__ = ['FontMetrics', 'METRICS_RESOURCE']

logger = logging.getLogger("cornish")

#: Name of the shipped table inside ``cornish.plot.data``.
METRICS_RESOURCE = "dejavu_sans_metrics.json"

#: The only table schema this module knows how to read.
SUPPORTED_SCHEMA = 1

_JUST_VERTICAL = ("T", "C", "B", "M")
_JUST_HORIZONTAL = ("L", "C", "R")


def _load_shipped_table() -> dict:
	'''
	Load the table shipped in ``cornish/plot/data/`` via importlib.resources.
	'''
	from importlib import resources
	with resources.files("cornish.plot.data").joinpath(METRICS_RESOURCE).open("r", encoding="utf-8") as stream:
		return json.load(stream)


class FontMetrics:
	'''
	Glyph-advance metrics for one font, in em units.

	:param table: a §6.2 table dict; ``None`` (the default) loads the shipped DejaVu Sans table
	:raises TypeError: if *table* is not a dict
	:raises ValueError: if *table* is missing required keys or carries an unsupported schema
	'''

	def __init__(self, table: Optional[dict] = None) -> None:
		if table is None:
			table = _load_shipped_table()
		if not isinstance(table, dict):
			raise TypeError(f"A font-metrics table must be a dict; got {type(table).__name__}.")

		schema = table.get("schema")
		if schema != SUPPORTED_SCHEMA:
			raise ValueError(f"Unsupported font-metrics table schema {schema!r} "
			                 f"(this cornish reads schema {SUPPORTED_SCHEMA}).")
		for key in ("font_family", "ascent", "descent", "advance", "default_advance"):
			if key not in table:
				raise ValueError(f"Font-metrics table is missing the required key '{key}'.")
		if not isinstance(table["advance"], dict) or not table["advance"]:
			raise ValueError("Font-metrics table key 'advance' must be a non-empty mapping.")

		self.font_family = str(table["font_family"])
		self.ascent = float(table["ascent"])
		self.descent = float(table["descent"])          # negative, per the hhea convention
		self.default_advance = float(table["default_advance"])
		self._advance = {character: float(width) for character, width in table["advance"].items()}
		#: glyphs already reported as uncovered — the diagnostic is once per glyph, not once per string
		self._reported_missing = set()

	# ------------------------------------------------------------------
	# widths
	# ------------------------------------------------------------------

	def advance_of(self, character: str) -> float:
		'''
		The advance width of one character, in em units.

		An uncovered glyph falls back to ``default_advance`` **with a logged
		diagnostic the first time that glyph is seen** (SPEC-09A §6.2) — the
		layout is approximate for that glyph, and saying so is the difference
		between a documented fallback and a silent one.
		'''
		width = self._advance.get(character)
		if width is None:
			if character not in self._reported_missing:
				self._reported_missing.add(character)
				logger.warning("Font-metrics table has no advance for U+%04X (%r); using the "
				               "default advance %.4f em. Text layout for strings containing this "
				               "glyph is approximate.", ord(character), character, self.default_advance)
			return self.default_advance
		return width

	def string_width(self, text: str, em: float) -> float:
		'''
		Width of *text* set at em size *em*, in the same units as *em*.

		:raises TypeError: if *text* is not a str
		:raises ValueError: if *em* is not finite and positive
		'''
		if not isinstance(text, str):
			raise TypeError(f"Text must be a str; got {type(text).__name__}.")
		em = float(em)
		if not math.isfinite(em) or em <= 0:
			raise ValueError(f"The em size must be a positive finite number; got {em!r}.")
		return sum(self.advance_of(character) for character in text) * em

	# ------------------------------------------------------------------
	# TxExt
	# ------------------------------------------------------------------

	def extents(self, text: str, x: float, y: float, just: str,
	            upx: float, upy: float, em: float) -> Tuple[float, ...]:
		'''
		The 8-float ``TxExt`` answer for *text* drawn at (*x*, *y*).

		Returns the four corners of the bounding box, x×4 then y×4,
		counter-clockwise from bottom-left — the order AST's Grf contract
		expects. The baseline math is astplot-js ``grfTxExt``'s (SPEC-09A §6.2):
		vertical ``T`` puts the box top at the anchor, ``C`` centres cap-middle,
		``B`` is the baseline, ``M`` puts the box bottom at the anchor;
		horizontal ``L``/``C``/``R`` shift by 0 / −W/2 / −W along the baseline
		direction.

		:param just: the 2-character justification (vertical then horizontal)
		:param upx: x component of the text up-vector
		:param upy: y component of the text up-vector
		:param em: em size of the text, in gbox units
		:raises ValueError: if *just* is not a legal 2-character code, the up-vector is degenerate, or a coordinate is not finite
		'''
		vertical, horizontal = self._parse_just(just)

		x = float(x)
		y = float(y)
		if not (math.isfinite(x) and math.isfinite(y)):
			raise ValueError(f"Text anchor must be finite; got ({x!r}, {y!r}).")

		up_length = math.hypot(float(upx), float(upy))
		if not math.isfinite(up_length) or up_length == 0:
			raise ValueError(f"The text up-vector must be non-zero and finite; got ({upx!r}, {upy!r}).")
		up_x, up_y = float(upx) / up_length, float(upy) / up_length
		# the baseline runs 90 degrees clockwise from "up" — identical to the
		# astplot-js grf-bridge convention
		base_x, base_y = up_y, -up_x

		if text == "":
			# a degenerate box at the anchor: an empty string occupies nothing,
			# and inventing a height for it would perturb AST's collision maths
			return (x, x, x, x, y, y, y, y)

		width = self.string_width(text, em)
		ascent = self.ascent * em
		descent = -self.descent * em            # descent is stored negative

		# horizontal: move the baseline origin so the box sits L/C/R of the anchor
		if horizontal == "L":
			shift = 0.0
		elif horizontal == "C":
			shift = -width / 2.0
		else:                                    # "R"
			shift = -width

		# vertical: move the baseline origin so the requested feature is at the anchor
		if vertical == "B":
			rise = 0.0
		elif vertical == "T":
			rise = -ascent
		elif vertical == "M":
			rise = descent
		else:                                    # "C" — cap-middle
			rise = -ascent / 2.0

		origin_x = x + shift * base_x + rise * up_x
		origin_y = y + shift * base_y + rise * up_y

		# corners, counter-clockwise from bottom-left
		bottom_left = (origin_x - descent * up_x, origin_y - descent * up_y)
		bottom_right = (bottom_left[0] + width * base_x, bottom_left[1] + width * base_y)
		top_left = (origin_x + ascent * up_x, origin_y + ascent * up_y)
		top_right = (top_left[0] + width * base_x, top_left[1] + width * base_y)

		return (bottom_left[0], bottom_right[0], top_right[0], top_left[0],
		        bottom_left[1], bottom_right[1], top_right[1], top_left[1])

	@staticmethod
	def _parse_just(just: str) -> Tuple[str, str]:
		'''
		Split and validate a 2-character justification code. Unknown codes raise
		— AST only ever sends legal ones, so anything else is a real bug and
		defaulting it would hide a mis-wired call site.
		'''
		if not isinstance(just, str):
			raise TypeError(f"Justification must be a 2-character str; got {type(just).__name__}.")
		text = just.strip().upper()
		if len(text) != 2:
			raise ValueError(f"Justification must be exactly 2 characters (vertical then horizontal); got {just!r}.")
		vertical, horizontal = text[0], text[1]
		if vertical not in _JUST_VERTICAL:
			raise ValueError(f"Vertical justification must be one of {_JUST_VERTICAL}; got {vertical!r} (from {just!r}).")
		if horizontal not in _JUST_HORIZONTAL:
			raise ValueError(f"Horizontal justification must be one of {_JUST_HORIZONTAL}; got {horizontal!r} (from {just!r}).")
		return vertical, horizontal
